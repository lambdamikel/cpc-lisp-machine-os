def glyphs():
    g = {}
    for line in G.strip("\n").split("\n"):
        key, rows = line[:3].strip(), line[3:].strip().split("|")
        code = int(key) if key.isdigit() and len(key) > 1 else ord(key)
        assert len(rows) == 8 and all(len(r) == 5 for r in rows), line
        g[code] = [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in rows]
    assert sorted(g) == list(range(32, 128)), sorted(set(range(32, 128)) - set(g))
    return g

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(__file__), "..", "..", "mach", "spectrum", "font.inc")
    g = glyphs()
    with open(out, "w") as f:
        f.write(";; made by tools/spectrum/mkfont.py: characters 32-127, 5 x 7 in 6 x 8\n")
        for c in range(32, 128):
            name = repr(chr(c)) if c < 127 else "DEL"
            f.write("    db " + ",".join("#%02X" % b for b in g[c]) + "   ; %d %s\n" % (c, name))

if __name__ == "__main__":
    main()
